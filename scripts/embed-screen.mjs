// Embeds the native helpers (helper/screen/main.swift for macOS, helper/screen/linux.c for Linux, helper/screen/windows.cs
// for Windows) into
// server/screen/helper-source.generated.ts.
// Plugin bundles are evaluated from memory, so the server cannot read files beside itself at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const root = new URL("..", import.meta.url);
const helpers = { darwin: "main.swift", linux: "linux.c", win32: "windows.cs" };
const entries = Object.entries(helpers).map(([platform, file]) => {
  const source = readFileSync(new URL(`helper/screen/${file}`, root), "utf8");
  const hash = createHash("sha256").update(source).digest("hex").slice(0, 16);
  console.log(`embedded helper/screen/${file} (${source.length} bytes, ${hash})`);
  return `  ${platform}: { file: ${JSON.stringify(file)}, hash: ${JSON.stringify(hash)}, source: ${JSON.stringify(source)} },`;
});
const output = `// Generated by scripts/embed-helper.mjs from helper/screen/. Do not edit.
export const HELPERS = {
${entries.join("\n")}
} as const;
`;
writeFileSync(new URL("server/screen/helper-source.generated.ts", root), output);

const rtc = readFileSync(new URL("helper/screen/webrtc.py", root), "utf8");
const rtcHash = createHash("sha256").update(rtc).digest("hex").slice(0, 16);
writeFileSync(new URL("server/screen/webrtc-source.generated.ts", root), `// Generated by scripts/embed-helper.mjs. Do not edit.\nexport const WEBRTC_HELPER = ${JSON.stringify({hash: rtcHash, source: rtc})} as const;\n`);
console.log(`embedded helper/screen/webrtc.py (${rtc.length} bytes, ${rtcHash})`);

const overlay = readFileSync(new URL("helper/control-overlay.py", root), "utf8");
const overlayHash = createHash("sha256").update(overlay).digest("hex").slice(0, 16);
writeFileSync(new URL("server/control/overlay-source.generated.ts", root), `// Generated by scripts/embed-screen.mjs. Do not edit.\nexport const CONTROL_OVERLAY = ${JSON.stringify({ hash: overlayHash, source: overlay })} as const;\n`);
